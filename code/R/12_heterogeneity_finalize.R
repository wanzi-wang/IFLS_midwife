frame <- read_intermediate("stage06", "analysis_sample")
tables_dir <- here::here("paper", "tables")
dir.create(tables_dir, recursive = TRUE, showWarnings = FALSE)

df <- frame |>
  filter(primary_sample == 1) |>
  mutate(
    sex_f = factor(sex, levels = c(1, 3),
                   labels = c("male", "female")),
    high_medu = as.integer(mother_edu_years >
                             stats::median(mother_edu_years,
                                           na.rm = TRUE)),
    young_mom = as.integer(mother_age_birth < 26),
    java_bali = as.integer(province %in% c(31L, 32L, 33L, 34L, 35L, 51L))
  )

outcomes <- c("health_index", "cognition_index",
              "depression_index", "bigfive_index")

coef_se <- function(m, var) {
  if (is.null(m) || !var %in% names(coef(m))) return(c(NA, NA))
  c(unname(coef(m)[var]),
    unname(sqrt(vcov(m)[var, var])))
}
fmt <- function(est, se) {
  if (is.na(est)) return("---")
  sprintf("%.3f\n(%.3f)", est, se)
}

# ---------------------------------------------------------------------
# 1. Three-panel heterogeneity: mother education, mother age, region.
# ---------------------------------------------------------------------
fit_subset <- function(y, d) {
  m <- feols(as.formula(sprintf(paste0(
    "%s ~ exposure_early_sar_legacy | ",
    "commid_birth_legacy + birth_year + source_wave"), y)),
    data = d, cluster = ~ commid_birth_legacy)
  p <- coef_se(m, "exposure_early_sar_legacy")
  fmt(p[1], p[2])
}

het_rows <- lapply(outcomes, function(y) {
  tibble(
    outcome     = y,
    medu_low    = fit_subset(y, df |> filter(high_medu == 0)),
    medu_high   = fit_subset(y, df |> filter(high_medu == 1)),
    age_young   = fit_subset(y, df |> filter(young_mom == 1)),
    age_older   = fit_subset(y, df |> filter(young_mom == 0)),
    region_java = fit_subset(y, df |> filter(java_bali == 1)),
    region_non  = fit_subset(y, df |> filter(java_bali == 0))
  )
})
het_tbl <- bind_rows(het_rows)

# Per-panel sample sizes for the footer rows.
n_subset <- function(d) format(nrow(d), big.mark = ",")
ns <- list(
  medu_low    = n_subset(df |> filter(high_medu == 0)),
  medu_high   = n_subset(df |> filter(high_medu == 1)),
  age_young   = n_subset(df |> filter(young_mom == 1)),
  age_older   = n_subset(df |> filter(young_mom == 0)),
  region_java = n_subset(df |> filter(java_bali == 1)),
  region_non  = n_subset(df |> filter(java_bali == 0))
)

cell_lines <- apply(
  het_tbl[, c("outcome", "medu_low", "medu_high", "age_young",
              "age_older", "region_java", "region_non")],
  1, function(r) {
    cells <- vapply(r[-1], function(cell)
      paste0("\\makecell{", gsub("\n", "\\\\\\\\", cell), "}"),
      character(1))
    sprintf("%s & %s \\\\", pretty_label(r["outcome"]),
            paste(cells, collapse = " & "))
  })

