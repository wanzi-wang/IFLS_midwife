# Heterogeneity dimensions:
#   * By mother education (low/high split at median)
#   * Forest plot across full / male / female / low-edu / high-edu.
#
# An earlier age-window TWFE specification was dropped: the age-window
# dummies are deterministic functions of birth_year * start_year, so
# conditioning on commid x birth-year FEs left them collinear within
# cell and the clustered SEs blew up past 1,000. The critical-period
# pattern is now delivered by the Callaway-Sant'Anna event-study
# figures in stage 09 (paper/figures/event_study_CS_*.pdf).
#
# Outputs:
#   paper/tables/heterogeneity_mother_edu.tex
#   paper/figures/heterogeneity_forest.pdf
#   paper/numbers.tex  — \newcommand for in-text numbers
