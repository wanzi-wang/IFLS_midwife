# ---------------------------------------------------------------------
# 2. Heterogeneity forest plot.
#    Run by-sex + by-mother-edu for each outcome; collect coefs; plot.
# ---------------------------------------------------------------------
forest_rows <- list()
for (y in outcomes) {
  subsets <- list(
    "Full sample" = df,
    "Male"        = df |> filter(sex == 1),
    "Female"      = df |> filter(sex == 3),
    "Low-edu"     = df |> filter(high_medu == 0),
    "High-edu"    = df |> filter(high_medu == 1)
  )
  for (nm in names(subsets)) {
    d <- subsets[[nm]]
    m <- feols(as.formula(sprintf(paste0(
      "%s ~ exposure_early_sar_legacy | ",
      "commid_birth_legacy + birth_year + source_wave"), y)),
      data = d, cluster = ~ commid_birth_legacy)
    p <- coef_se(m, "exposure_early_sar_legacy")
    forest_rows[[paste(y, nm)]] <- tibble(
      outcome = y, subgroup = nm,
      estimate = p[1], se = p[2],
      ci_lo = p[1] - 1.96 * p[2], ci_hi = p[1] + 1.96 * p[2]
    )
  }
}
forest <- bind_rows(forest_rows) |>
  mutate(
    outcome = factor(outcome, levels = outcomes,
                     labels = c("Health index",
                                "Cognition index",
                                "Depression index (higher = better)",
                                "Socioemotional index")),
    subgroup = factor(subgroup, levels = rev(c("Full sample",
                                               "Male", "Female",
                                               "Low-edu", "High-edu")))
  )

# Visual identity mirrors the CS event-study plot in stage 09:
# theme_bw, blue point + errorbar, black dashed zero line, no minor
# gridlines. Consistent palette keeps the reader oriented across the
# paper's three figures.
palette_oi <- c(blue = "#0072B2", vermilion = "#D55E00", black = "#000000")

p_forest <- ggplot(forest,
                   aes(x = estimate, y = subgroup)) +
  geom_vline(xintercept = 0, linetype = "dashed",
             colour = palette_oi["black"], alpha = 0.5) +
  geom_errorbar(aes(xmin = ci_lo, xmax = ci_hi),
                orientation = "y", width = 0.2,
                colour = palette_oi["blue"], linewidth = 0.5) +
  geom_point(size = 2, colour = palette_oi["blue"]) +
  facet_wrap(~ outcome, ncol = 2, scales = "free_x") +
  labs(x = "Effect of early village-midwife exposure (SD)",
       y = NULL) +
  theme_bw(base_size = 11) +
  theme(panel.grid.minor = element_blank())

ggsave(file.path(figures_dir, "heterogeneity_forest.pdf"),
       plot = p_forest, width = 6.5, height = 4.5, units = "in",
       device = cairo_pdf, bg = "white")

