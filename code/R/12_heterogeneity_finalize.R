outcomes <- c("health_index", "cognition_index",
              "depression_index", "bigfive_index")

coef_se <- function(m, var) {
  if (is.null(m) || !var %in% names(coef(m))) return(c(NA, NA))
  c(unname(coef(m)[var]),
    unname(sqrt(vcov(m)[var, var])))
}
fmt <- function(est, se) {
  if (is.na(est)) return("---")
  sprintf("%.3f\n(%.3f)", est, se)
}

# ---------------------------------------------------------------------
# 1. Heterogeneity by mother education.
# ---------------------------------------------------------------------
rows_edu <- lapply(outcomes, function(y) {
  ml <- feols(as.formula(sprintf(paste0(
    "%s ~ exposure_early_sar_legacy | ",
    "commid_birth_legacy + birth_year + source_wave"), y)),
    data = df |> filter(high_medu == 0),
    cluster = ~ commid_birth_legacy)
  mh <- feols(as.formula(sprintf(paste0(
    "%s ~ exposure_early_sar_legacy | ",
    "commid_birth_legacy + birth_year + source_wave"), y)),
    data = df |> filter(high_medu == 1),
    cluster = ~ commid_birth_legacy)
  pl <- coef_se(ml, "exposure_early_sar_legacy")
  ph <- coef_se(mh, "exposure_early_sar_legacy")
  tibble(outcome = y,
         `Low-edu`  = fmt(pl[1], pl[2]),
         `High-edu` = fmt(ph[1], ph[2]))
})
edu_tbl <- bind_rows(rows_edu)

writeLines(c(
  "% Auto-generated by code/R/12_heterogeneity_finalize.R",
  "\\begin{tabular}{lcc}",
  "\\toprule",
