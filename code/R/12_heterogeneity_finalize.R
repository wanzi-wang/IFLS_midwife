# ---------------------------------------------------------------------
# 2. numbers.tex — in-text macros for paper.tex and paper_predoc.tex.
#
# CS macros are pulled from stage 08's persisted att_gt objects so the
# abstract's headline values trace back to the same estimator that
# populates main_results.tex. TWFE baseline macros are recomputed here
# on the same non-migrant frame; sibling-FE macro comes from a fresh
# mother-FE fit on the >=2-sibling subsample to match the robustness
# table. Every macro below must map to a cited \macro somewhere in
# paper/sections; unused macros should be pruned to keep the file honest.
# ---------------------------------------------------------------------
stage08 <- readRDS(here::here("data", "output", "regressions",
                              "stage08_models.rds"))

# TWFE baseline (used as the "TWFE is the wrong lens" benchmark in the
# CS-vs-TWFE comparison paragraphs).
main_m <- feols(health_index ~ exposure_early_sar_legacy |
                  commid_birth_legacy + birth_year + source_wave,
                data = df, cluster = ~ commid_birth_legacy)
dep_m  <- feols(depression_index ~ exposure_early_sar_legacy |
                  commid_birth_legacy + birth_year + source_wave,
                data = df, cluster = ~ commid_birth_legacy)

# Within-mother (sibling-FE) depression, parallel to stage 10's spec A.
sib_m <- feols(depression_index ~ exposure_early_sar_legacy +
                 birth_order + mother_age_birth |
                 mother_pidlink + birth_year,
               data = df |>
                 filter(!is.na(mother_pidlink)) |>
                 group_by(mother_pidlink) |>
                 filter(n() >= 2) |>
                 mutate(birth_order = rank(birth_year,
                                           ties.method = "first")) |>
                 ungroup(),
               cluster = ~ commid_birth_legacy)

